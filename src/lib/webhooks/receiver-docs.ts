export const WEBHOOK_SIGNATURE_HEADER = "X-Webhook-Signature";

export const WEBHOOK_SIGNATURE_FORMULA =
  "hex(HMAC_SHA256(secret, `${timestamp}.${rawBody}`))";

export const WEBHOOK_RECEIVER_DOCS_SNIPPET = [
  'import { createHmac, timingSafeEqual } from "node:crypto";',
  "",
  'const SIGNATURE_HEADER = "x-webhook-signature";',
  "const TOLERANCE_SECONDS = 5 * 60;",
  "",
  "function verifyFlareWebhook(rawBody, header, signingSecret) {",
  "  const parts = Object.fromEntries(",
  '    header.split(",").map((part) => {',
  '      const [key, value] = part.trim().split("=");',
  "      return [key, value];",
  "    }),",
  "  );",
  "",
  "  const timestamp = Number(parts.t);",
  "  if (!timestamp || !parts.v1) return false;",
  "",
  "  const age = Math.abs(Math.floor(Date.now() / 1000) - timestamp);",
  "  if (age > TOLERANCE_SECONDS) return false;",
  "",
  '  const expected = createHmac("sha256", signingSecret)',
  "    .update(`${timestamp}.${rawBody}`)",
  '    .digest("hex");',
  "",
  '  const expectedBytes = Buffer.from(expected, "hex");',
  '  const actualBytes = Buffer.from(parts.v1, "hex");',
  "  return (",
  "    expectedBytes.length === actualBytes.length &&",
  "    timingSafeEqual(expectedBytes, actualBytes)",
  "  );",
  "}",
  "",
  "export async function POST(request) {",
  "  const rawBody = await request.text();",
  '  const signature = request.headers.get(SIGNATURE_HEADER) ?? "";',
  "",
  "  if (!verifyFlareWebhook(rawBody, signature, process.env.FLARE_WEBHOOK_SECRET)) {",
  '    return new Response("Invalid signature", { status: 401 });',
  "  }",
  "",
  "  const event = JSON.parse(rawBody);",
  "  // Handle event.eventType and event.payload here.",
  "  return Response.json({ ok: true });",
  "}",
].join("\n");
